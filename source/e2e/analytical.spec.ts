test('recollection creates a new physical specimen and preserves the rejected accession', async ({ page }) => {
  test.setTimeout(120_000);
  page.on('dialog', dialog => void dialog.accept());
  await login(page, 'clerk');
  await page.goto('/patients/70000000-0000-4000-8000-000000000001');
  await page.getByRole('link', { name: 'Create order', exact: true }).click();
  await page.getByRole('button', { name: /Glucose \(demo\)/ }).click();
  await page.getByRole('button', { name: 'Create order', exact: true }).click();
  await expect(page).toHaveURL(/\/orders\/[^/]+$/);
  await page.getByRole('button', { name: 'Generate specimen', exact: true }).click();
  await page.getByRole('link', { name: 'View attempt', exact: true }).click();
  const firstSpecimenPath = new URL(page.url()).pathname;
  const firstBarcode = await page.locator('.identifier-large').first().innerText();
  await page.getByRole('button', { name: 'Mark collected', exact: true }).click();
  await page.getByRole('button', { name: 'Receive & generate accession', exact: true }).click();
  await expect(page.locator('.identifier-large')).toHaveCount(2);
  const rejectedAccession = await page.locator('.identifier-large').last().innerText();
  expect(rejectedAccession).toMatch(/^ACC-/);
  await page.getByLabel('Rejection reason').fill('Synthetic transport damage for lineage demo');
  await page.getByRole('button', { name: 'Reject specimen', exact: true }).click();
  await page.getByLabel('Recollection reason').fill('New physical tube required for demo');
  await page.getByRole('button', { name: 'Request recollection', exact: true }).click();
  await expect(page.getByText('Recollection required', { exact: true }).first()).toBeVisible();

  await page.getByRole('link', { name: 'Open order for replacement' }).click();
  await expect(page.getByRole('heading', { name: 'Collection attempts' })).toBeVisible();
  await page.getByRole('button', { name: 'Generate replacement specimen', exact: true }).click();
  await expect(page.getByText(/ATTEMPT 2/).first()).toBeVisible();
  await page.screenshot({ path: '.runtime/ux-collection-attempts.png', fullPage: true, animations: 'disabled' });
  const specimenPaths = await page.locator('a[href^="/specimens/"]').evaluateAll(links =>
    links.map(link => link.getAttribute('href')).filter((path): path is string => Boolean(path)));
  const secondSpecimenPath = specimenPaths.find(path => path !== firstSpecimenPath);
  expect(secondSpecimenPath).toBeTruthy();
  await page.goto(secondSpecimenPath!);
  const replacementBarcode = await page.locator('.identifier-large').first().innerText();
  expect(replacementBarcode).not.toBe(firstBarcode);
  await page.getByRole('button', { name: 'Mark collected', exact: true }).click();
  await page.getByRole('button', { name: 'Receive & generate accession', exact: true }).click();
  await expect(page.locator('.identifier-large')).toHaveCount(2);
  const acceptedAccession = await page.locator('.identifier-large').last().innerText();
  expect(acceptedAccession).toMatch(/^ACC-/);
  expect(acceptedAccession).not.toBe(rejectedAccession);
  await page.getByRole('button', { name: 'Accept specimen', exact: true }).click();
  await expect(page.getByText('Accepted and ready for analytical processing.')).toBeVisible();

  await page.goto('/accessions');
  await page.getByLabel('Accession identifier').fill(rejectedAccession);
  await page.getByRole('button', { name: 'Lookup', exact: true }).click();
  await expect(page.getByText('MATCHED ACCESSION', { exact: true })).toBeVisible();
  await expect(page.getByText(rejectedAccession, { exact: true }).first()).toBeVisible();
  await expect(page.getByText(/Accession decision:\s*Rejected/)).toBeVisible();
  await expect(page.getByRole('link', { name: 'See all collection attempts' })).toBeVisible();
  await page.screenshot({ path: '.runtime/ux-historical-accession.png', fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ path: '.runtime/ux-historical-accession-mobile.png', fullPage: true, animations: 'disabled' });
});

test('administrator workspace does not expose laboratory data', async ({ page }) => {
  const laboratoryRequests: string[] = [];
  page.on('request', request => { if (/\/api\/v1\/(patients|orders|specimens|results)/.test(request.url())) laboratoryRequests.push(request.url()); });
  await login(page, 'admin');
  await expect(page.getByRole('link', { name: 'Patients', exact: true })).toHaveCount(0);
  await expect(page.getByRole('link', { name: 'Results', exact: true })).toHaveCount(0);
  await page.getByRole('link', { name: 'Open configuration', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Facility settings' })).toBeVisible();
  expect(laboratoryRequests).toEqual([]);
});
